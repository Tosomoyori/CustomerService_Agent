_CJK_RE = re.compile(r"[\u4e00-\u9fff]")
_ASCII_WORD_RE = re.compile(r"[A-Za-z]{2,}")


@lru_cache(maxsize=1)
def _compiled_word_patterns():
    return sorted(_CANTON_WORDS.items(), key=lambda kv: -len(kv[0]))


def detect_language(text: str) -> str:
    """识别输入语言。

    规则：
    1. 无 CJK 字符 → en；
    2. 含粤语标记字（唔/嘅/咗/喺/冇/佢/哋/啲/咁/睇/諗/嘢/咩/嚟/搵）→ zh-HK；
    3. 含繁体字 → zh-HK（繁体默认视为香港用户，与业务市场一致）；
    4. 其余 → zh-CN。
    """
    stripped = (text or "").strip()
    if not stripped:
        return LANG_ZH_HK  # 空输入按默认市场语言处理

    has_cjk = bool(_CJK_RE.search(stripped))
    ascii_words = len(_ASCII_WORD_RE.findall(stripped))
    if not has_cjk:
        return LANG_EN if ascii_words > 0 else LANG_ZH_HK

    canton_markers = set("唔嘅咗喺冇佢哋啲咁睇諗嘢咩嚟搵")
    if any(ch in canton_markers for ch in stripped):
        return LANG_ZH_HK

    # 粤语词表已覆盖的组合词也视为粤语
    for word in _CANTON_WORDS:
        if word in stripped:
            return LANG_ZH_HK

    trad_chars = set(_TRAD_SIMP) | set(_CANTON_CHARS)
    if any(ch in trad_chars for ch in stripped):
        return LANG_ZH_HK

    return LANG_ZH_CN


def normalize(text: str) -> str:
    """检索/路由归一化：粤语词 → 普通话，再通用繁→简。"""
    out = text or ""
    for word, simplified in _compiled_word_patterns():
        out = out.replace(word, simplified)
    chars = []
    for ch in out:
        if ch in _CANTON_CHARS:
            chars.append(_CANTON_CHARS[ch])
        elif ch in _TRAD_SIMP:
            chars.append(_TRAD_SIMP[ch])
        else:
            chars.append(ch)
    return "".join(chars)
